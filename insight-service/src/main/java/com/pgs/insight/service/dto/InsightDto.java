package com.pgs.insight.service.dto;

import io.swagger.v3.oas.annotations.media.Schema;
import lombok.Builder;

/**
 * Data Transfer Object representing a generated energy insight for a user.
 * <p>
 * This record encapsulates the identifier of the user, the textual insight
 * produced by the chat model and the aggregated energy usage over the analysed
 * period. It is immutable and can be constructed using the {@code @Builder}
 * annotation provided by Lombok.
 *
 * @param userId      Unique identifier of the user the insight refers to.
 * @param tips        Energy-saving tips or overview generated by the chat model.
 * @param energyUsage Total energy consumed by the user devices over the analysed period.
 */
@Builder
@Schema(description = "Generated energy insight for a user")
public record InsightDto(
        @Schema(description = "User id", example = "1")
        Long userId,

        @Schema(description = "Energy-saving tips or overview generated by the chat model",
                example = "Consider shifting heavy loads to off-peak hours and unplugging idle devices.")
        String tips,

        @Schema(description = "Total energy consumed by the user devices over the analysed period (kWh)",
                example = "12.75")
        double energyUsage
) {
}
